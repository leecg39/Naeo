import {test,type TestContext} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {openDatabase} from '../../src/server/database';
import {createApi} from '../../src/server/api';
import {runCitationOnce} from '../../src/server/citations/worker';

const origin='http://127.0.0.1:3000';process.env.NAEO_APP_URL=origin;
function fixture(t:TestContext){
 const db=openDatabase(':memory:');t.after(()=>db.close());const handler=createApi(()=>db);
 const send=(path:string,method='GET',payload?:unknown,cookie?:string,requestOrigin=origin)=>handler(new Request(origin+path,{method,headers:{Origin:requestOrigin,'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(payload!==undefined?{body:JSON.stringify(payload)}:{})}));
 const member=async(email:string)=>{const r=await send('/api/auth/register','POST',{email,password:'citation-http-password',nickname:'인용 검사',termsAccepted:true});assert.equal(r.status,201);return{cookie:r.headers.get('set-cookie')!.split(';')[0],id:(await r.json()).data.user.id as string};};
 const saved={provider:process.env.NAEO_CITATION_PROVIDER,key:process.env.NAEO_SERPAPI_KEY};
 t.after(()=>{for(const [k,v] of [['NAEO_CITATION_PROVIDER',saved.provider],['NAEO_SERPAPI_KEY',saved.key]] as const){if(v===undefined)delete process.env[k];else process.env[k]=v;}});
 const configure=(on:boolean)=>{if(on){process.env.NAEO_CITATION_PROVIDER='serpapi';process.env.NAEO_SERPAPI_KEY='h'.repeat(40);}else{delete process.env.NAEO_CITATION_PROVIDER;delete process.env.NAEO_SERPAPI_KEY;}};
 return{db,send,member,configure};
}
const data=async(r:Response)=>(await r.json()).data;

test('citation HTTP: authentication, origin, strict input, configuration and isolation',async t=>{
 const f=fixture(t),a=await f.member('a@example.test'),b=await f.member('b@example.test');
 assert.equal((await f.send('/api/citations')).status,401);
 const blog=await data(await f.send('/api/blogs','POST',{naverId:'http_cite',title:'블로그'},a.cookie));
 const post=randomUUID();
 f.db.prepare("INSERT INTO blog_posts(id,blog_id,external_id,url,title,excerpt,category,tags_json,published_at,collected_at) VALUES(?,?,'5','https://blog.naver.com/http_cite/5','제주 여행 코스','','여행','[\"제주 여행\"]',1,1)").run(post,blog.id);
 f.configure(false);
 const idle=await data(await f.send('/api/citations','GET',undefined,a.cookie));
 assert.equal(idle.configured,false);assert.equal(idle.blog.id,blog.id);assert.equal(idle.report,null);
 assert.equal((await f.send('/api/citations/runs','POST',{blogId:blog.id},a.cookie)).status,503);
 f.configure(true);
 assert.equal((await f.send('/api/citations/runs','POST',{blogId:blog.id},a.cookie,'https://evil.example')).status,403);
 assert.equal((await f.send('/api/citations/runs','POST',{blogId:blog.id,ownerId:b.id},a.cookie)).status,400);
 assert.equal((await f.send('/api/citations/runs','POST',{blogId:blog.id},b.cookie)).status,404);
 assert.equal((await f.send('/api/citations?blogId='+blog.id,'GET',undefined,b.cookie)).status,404);
 assert.equal((await f.send('/api/citations?ownerId=x','GET',undefined,a.cookie)).status,400);
 assert.equal((await f.send('/api/citations','POST',{},a.cookie)).status,405);
 const created=await f.send('/api/citations/runs','POST',{blogId:blog.id,idempotencyKey:'same'},a.cookie);
 assert.equal(created.status,201);const run=await data(created);
 assert.equal((await data(await f.send('/api/citations/runs','POST',{blogId:blog.id,idempotencyKey:'same'},a.cookie))).id,run.id);
 assert.equal((await f.send('/api/citations/runs','POST',{blogId:blog.id},a.cookie)).status,409);
 assert.equal((await f.send(`/api/citations/runs/${run.id}`,'GET',undefined,b.cookie)).status,404);
 assert.equal((await f.send(`/api/citations/runs/${run.id}`,'DELETE',undefined,a.cookie)).status,405);
 await runCitationOnce(f.db,'w',async()=>({searches:1,links:[],briefing:{markdown:'요약',references:[{index:1,title:'내 글',link:'https://blog.naver.com/http_cite/5',source:'블로그',snippet:''}],media:[],questions:['다음 질문']}}));
 const done=await data(await f.send(`/api/citations/runs/${run.id}`,'GET',undefined,a.cookie));
 assert.equal(done.state,'succeeded');
 assert.equal((await f.send(`/api/citations/runs/${run.id}/cancel`,'POST',undefined,a.cookie)).status,409);
 const overview=await data(await f.send('/api/citations','GET',undefined,a.cookie));
 assert.equal(overview.report.cited,1);
 const result=overview.report.rows[0];
 assert.equal((await f.send(`/api/citations/results/${result.id}`,'GET',undefined,b.cookie)).status,404);
 assert.equal((await f.send(`/api/citations/results/${result.id}/viewed`,'POST',undefined,b.cookie)).status,404);
 const detail=await data(await f.send(`/api/citations/results/${result.id}`,'GET',undefined,a.cookie));
 assert.equal(detail.briefingDetail.references[0].samePost,true);assert.equal(detail.viewedAt,null);
 assert.equal((await f.send(`/api/citations/results/${result.id}/viewed`,'POST',undefined,a.cookie,'https://evil.example')).status,403);
 assert.equal((await f.send('/api/tutorial/finish','POST',{step:'ai_picks'},a.cookie)).status,409,'locked until the detail is opened');
 assert.ok((await data(await f.send(`/api/citations/results/${result.id}/viewed`,'POST',undefined,a.cookie))).viewedAt>0);
 assert.equal((await data(await f.send('/api/tutorial/finish','POST',{step:'ai_picks'},a.cookie))).awarded,30);
 assert.equal((await f.send(`/api/citations/keywords/${post}`,'PUT',{keyword:'제주 3박',version:0},b.cookie)).status,404);
 assert.equal((await f.send(`/api/citations/keywords/${post}`,'PUT',{keyword:'제주 3박',version:0,extra:1},a.cookie)).status,400);
 const kw=await data(await f.send(`/api/citations/keywords/${post}`,'PUT',{keyword:'제주 3박',version:0},a.cookie));
 assert.deepEqual(kw,{keyword:'제주 3박',source:'member',version:1});
 assert.equal((await f.send(`/api/citations/keywords/${post}`,'PUT',{keyword:'제주 4박',version:0},a.cookie)).status,409);
 assert.equal((await f.send(`/api/citations/keywords/${post}`,'GET',undefined,a.cookie)).status,405);
 assert.deepEqual(await data(await f.send(`/api/citations/keywords/${post}`,'DELETE',{version:1},a.cookie)),{keyword:'제주 여행',source:'tag',version:0});
 const raw=await f.send('/api/citations/runs','POST',undefined,a.cookie);
 assert.equal(raw.status,400,'a body is required to choose the blog');
 f.db.prepare('UPDATE users SET terms_accepted_at=0 WHERE id=?').run(a.id);
 assert.equal((await f.send('/api/citations','GET',undefined,a.cookie)).status,403);
});
